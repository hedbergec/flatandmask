#' JsonCSVMaskr: deterministic masking for JSON and CSV data
#'
#' JsonCSVMaskr is an R translation of the PowerShell Flat & Mask data masking
#' tool. It masks selected CSV columns or JSON field paths with deterministic
#' HMAC-SHA256 values, writes a masking key, preserves a masked JSON copy when
#' applicable, normalizes nested JSON into related CSV tables, and includes a
#' Shiny interface.
#'
#' @section Supported input shapes:
#' CSV files with headers; ordinary JSON objects; arrays of JSON objects;
#' NDJSON, JSON Lines, comma-separated loose objects, and concatenated objects;
#' Socrata exports with `meta.view.columns` and row-array `data`; GeoJSON
#' `FeatureCollection` objects; envelope collections under `data`, `results`,
#' `items`, or `records`; and top-level header-row array JSON.
#'
#' @section Masking behavior:
#' Masked values are the first 12 Base64 characters of an HMAC-SHA256 digest of
#' the original value using the supplied secret key. The same original value and
#' key always produce the same masked value. Empty values remain empty.
#'
