#' Run a complete masking job
#'
#' `datamaskr()` is the primary scripted interface. It resets package state,
#' detects whether the input is CSV or one of the supported JSON shapes, masks
#' selected fields, writes output files, and mirrors progress through console
#' status messages or an optional callback.
#'
#' `invoke_masking()` is retained as a compatibility alias for replication
#' scripts generated by earlier versions of JsonCSVMaskr and the original
#' PowerShell tool.
#'
#' @param input_file Path to a `.csv` or `.json` file.
#' @param output_folder Directory where output files should be written.
#' @param key_file Path for the masking key CSV. Defaults to
#'   `masking_key.csv` inside `output_folder`.
#' @param secret_key Secret key used as the HMAC-SHA256 key. Reusing the same
#'   key with the same input value gives the same masked value.
#' @param mask_fields Character vector of CSV column names or JSON field paths
#'   to mask. JSON paths may include or omit the `root.` prefix.
#' @param progress_callback Optional function called as
#'   `progress_callback(stage, current, total, message)`, where `stage` is one
#'   of `"load"`, `"mask"`, `"normalize"`, or `"export"`.
#'
#' @return Invisibly returns `output_folder`. Files are written for their side
#'   effects. CSV jobs write `data.csv`, `masking_key.csv`, and
#'   `replicate_masking.R`. JSON jobs also write a masked JSON/NDJSON file and
#'   normalized CSV tables.
#'
#' @examples
#' input <- tempfile(fileext = ".csv")
#' writeLines(c("name,email", "Alice,alice@example.com"), input)
#' out <- tempfile()
#' datamaskr(input, out, secret_key = "demo", mask_fields = "email")
#' list.files(out)
#'
#' @seealso [json_helpers], [csv_helpers], [shiny_app]
#' @name datamaskr
#' @aliases invoke_masking
#' @usage
#' datamaskr(input_file, output_folder,
#'   key_file = file.path(output_folder, "masking_key.csv"),
#'   secret_key, mask_fields, progress_callback = NULL)
#'
#' invoke_masking(input_file, output_folder,
#'   key_file = file.path(output_folder, "masking_key.csv"),
#'   secret_key, mask_fields, progress_callback = NULL)
